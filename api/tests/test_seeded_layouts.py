"""Every seeded layout profile is a body `POST /layouts` would accept.

A `statement_layout` row is household-scoped and validated by `LayoutCreate`, so `db/seeds/`
holds profiles as request bodies rather than as inserts — `db/seeds/README.md` says why, and
says what a raw insert would bypass: band ordering, sign-convention agreement, the quirks
vocabulary, regex compilation. Nothing applies these files automatically, which is exactly how
they drift: a seed is edited by hand and applied by hand, and the first thing to notice a
profile the endpoint refuses is the owner, mid-import.

`test_ingest_card_frame.py` held the one profile that existed to that shape, as a side effect
of building on it. This holds every profile there will be — slice 1.2 adds three more, one per
bank — so a layout seeded without a frame test of its own is covered on the day it lands rather
than on the day someone remembers.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any
from uuid import UUID

import pytest

from oneledger.institutions import resolve_institution
from oneledger.routes.layouts import LayoutCreate

SEEDS = Path(__file__).resolve().parents[2] / "db" / "seeds"
PROFILES = sorted(SEEDS.glob("*.json"))
EXPECTED_ACCOUNT_TYPES = {
    "account-layout": "current",
    "card-layout": "credit_card",
    "ledger-layout": "savings",
    "passbook-layout": "savings",
}
ACCOUNT_CAPTURE_EXAMPLES = {
    "account-layout": ("Account No. 1111222233334", "1111222233334"),
    "card-layout": ("Card Number: 1111 XXXX XXXX 2222", "2222"),
    "ledger-layout": ("Account No.:11112222333344", "11112222333344"),
    "passbook-layout": ("Statement for Account No :1111222233", "1111222233"),
}
CURRENCY_CAPTURE_EXAMPLES = {
    "account-layout": "Account Currency XAA",
    "card-layout": "Currency : XAA",
    "ledger-layout": "Account Currency:XAA",
}
INSTITUTION_CAPTURE_EXAMPLES = {
    "account-layout": ("Emirates NBD", "Emirates"),
    "card-layout": ("Emirates NBD", "Emirates NBD"),
    "ledger-layout": ("HDFCBANK Limited", "HDFC"),
    "passbook-layout": ("AXIS BANK Limited", "AXIS"),
}
INSTITUTION_RESOLUTION = {
    "account-layout": ("Emirates NBD", "ENBD", "AE", "needs_confirmation"),
    "card-layout": ("Emirates NBD", "ENBD", "AE", "matched"),
    "ledger-layout": ("HDFC Bank", "HDFC", "IN", "matched"),
    "passbook-layout": ("Axis Bank", "Axis", "IN", "matched"),
}


class InstitutionCursor:
    def __init__(self, row: tuple[Any, ...]) -> None:
        self.row = row

    def execute(self, _statement: str, _values: tuple[Any, ...]) -> None:
        pass

    def fetchall(self) -> list[tuple[Any, ...]]:
        return [self.row]


def _profile(path: Path) -> dict[str, Any]:
    values: dict[str, Any] = json.loads(path.read_text())
    return values


def test_the_seed_directory_holds_profiles_to_check() -> None:
    """The guard on the guard.

    A glob that matches nothing parametrizes to nothing and reports green, so without this the
    suite would go on passing after a rename, a move or a directory that stopped being shipped —
    reporting that every profile is valid while checking none.
    """
    assert PROFILES, f"no layout profile found in {SEEDS}"


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_is_a_body_the_endpoint_accepts(path: Path) -> None:
    LayoutCreate.model_validate(_profile(path))


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_names_no_institution(path: Path) -> None:
    """`institution.id` is generated by the database that inserted it.

    `db/seeds/institutions.sql` inserts without ids, so every institution's key is whatever
    `gen_random_uuid()` produced on that machine. A profile exported from a database where the
    layout was mapped carries that key, and on any other database it is either a foreign key
    that does not resolve or — worse, because nothing complains — a key that resolves to a
    different institution. A seeded profile leaves it out; the mapper UI sets it per household
    when it arrives (slice 1.7).
    """
    assert _profile(path).get("institutionId") is None


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_declares_its_account_type(path: Path) -> None:
    assert _profile(path).get("accountType") == EXPECTED_ACCOUNT_TYPES[path.stem]


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_captures_an_account_identity(path: Path) -> None:
    patterns = _profile(path).get("metadataPatterns") or {}
    expected_key = "account_number_masked" if path.stem == "card-layout" else "account_number"
    assert set(patterns) & {"account_number", "account_number_masked"} == {expected_key}
    pattern = patterns.get(expected_key)
    assert pattern is not None
    assert re.compile(pattern).groups == 1
    sample, expected = ACCOUNT_CAPTURE_EXAMPLES[path.stem]
    matched = re.search(pattern, sample, re.IGNORECASE | re.MULTILINE)
    assert matched is not None
    assert matched.group(1) == expected


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_captures_only_generic_public_issuer_text(path: Path) -> None:
    pattern = (_profile(path).get("metadataPatterns") or {}).get("institution_name")
    assert pattern is not None
    assert re.compile(pattern).groups == 1
    sample, expected = INSTITUTION_CAPTURE_EXAMPLES[path.stem]
    matched = re.search(pattern, sample, re.IGNORECASE | re.MULTILINE)
    assert matched is not None
    assert matched.group(1) == expected
    assert not re.search(r"\d", matched.group(1))
    name, short_name, country, expected_status = INSTITUTION_RESOLUTION[path.stem]
    institution_id = UUID("aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa")
    resolution = resolve_institution(
        InstitutionCursor(
            (institution_id, name, short_name, country, "bank", None, None, None, None)
        ),
        UUID("bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"),
        matched.group(1),
    )
    assert resolution.status == expected_status
    assert [candidate.id for candidate in resolution.candidates] == (
        [institution_id] if expected_status == "matched" else []
    )


@pytest.mark.parametrize(
    "profile_name,sample", CURRENCY_CAPTURE_EXAMPLES.items(), ids=CURRENCY_CAPTURE_EXAMPLES
)
def test_a_seeded_profile_captures_currency_when_the_statement_prints_it(
    profile_name: str, sample: str
) -> None:
    profile = _profile(SEEDS / f"{profile_name}.json")
    pattern = (profile.get("metadataPatterns") or {}).get("currency")
    assert pattern is not None
    matched = re.search(pattern, sample, re.IGNORECASE | re.MULTILINE)
    assert matched is not None
    assert matched.group(1) == "XAA"


def test_card_layout_captures_the_lowercase_currency_label_used_by_local_statements() -> None:
    profile = _profile(SEEDS / "card-layout.json")
    pattern = profile["metadataPatterns"]["currency"]

    matched = re.search(pattern, "currency : XAA", re.MULTILINE)

    assert matched is not None
    assert matched.group(1) == "XAA"


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_no_seeded_pattern_contains_a_literal_identifier(path: Path) -> None:
    profile = _profile(path)
    patterns = [
        *profile["fingerprints"],
        *(profile.get("skipLinePatterns") or []),
        *(profile.get("metadataPatterns") or {}).values(),
        profile.get("headerRowPattern"),
        profile.get("openingBalancePattern"),
        profile.get("closingBalancePattern"),
    ]
    assert not any(re.search(r"\d{5,}", pattern) for pattern in patterns if pattern is not None)
