"""Every seeded layout profile is a body `POST /layouts` would accept.

A `statement_layout` row is household-scoped and validated by `LayoutCreate`, so `db/seeds/`
holds profiles as request bodies rather than as inserts — `db/seeds/README.md` says why, and
says what a raw insert would bypass: band ordering, sign-convention agreement, the quirks
vocabulary, regex compilation. Nothing applies these files automatically, which is exactly how
they drift: a seed is edited by hand and applied by hand, and the first thing to notice a
profile the endpoint refuses is the owner, mid-import.

`test_ingest_card_frame.py` held the one profile that existed to that shape, as a side effect
of building on it. This holds every profile there will be — slice 1.2 adds three more, one per
bank — so a layout seeded without a frame test of its own is covered on the day it lands rather
than on the day someone remembers.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from oneledger.routes.layouts import LayoutCreate

SEEDS = Path(__file__).resolve().parents[2] / "db" / "seeds"
PROFILES = sorted(SEEDS.glob("*.json"))


def _profile(path: Path) -> dict[str, Any]:
    values: dict[str, Any] = json.loads(path.read_text())
    return values


def test_the_seed_directory_holds_profiles_to_check() -> None:
    """The guard on the guard.

    A glob that matches nothing parametrizes to nothing and reports green, so without this the
    suite would go on passing after a rename, a move or a directory that stopped being shipped —
    reporting that every profile is valid while checking none.
    """
    assert PROFILES, f"no layout profile found in {SEEDS}"


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_is_a_body_the_endpoint_accepts(path: Path) -> None:
    LayoutCreate.model_validate(_profile(path))


@pytest.mark.parametrize("path", PROFILES, ids=lambda path: path.stem)
def test_a_seeded_profile_names_no_institution(path: Path) -> None:
    """`institution.id` is generated by the database that inserted it.

    `db/seeds/institutions.sql` inserts without ids, so every institution's key is whatever
    `gen_random_uuid()` produced on that machine. A profile exported from a database where the
    layout was mapped carries that key, and on any other database it is either a foreign key
    that does not resolve or — worse, because nothing complains — a key that resolves to a
    different institution. A seeded profile leaves it out; the mapper UI sets it per household
    when it arrives (slice 1.7).
    """
    assert _profile(path).get("institutionId") is None
